"""PaperSpec -> a runnable project directory.

Everything except model.py is a fixed scaffold driven by config.yaml. Only the
paper-specific module is generated, and it is generated from the spec rather
than from the paper text.
"""
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import yaml

from . import emit
from .config import CODEGEN, SCAFFOLD_DIR
from .llm import extract_code, generate
from .spec import PaperSpec, to_runtime_config

SYSTEM = """\
You write a single PyTorch module file from a structured model specification.

Contract, enforced by the surrounding project:
- Define `build_model(cfg: dict) -> torch.nn.Module` and nothing else public.
- `cfg["input_shape"]` is the input shape without the batch dimension;
  `cfg["output_dim"]` is the number of output units.
- The returned module must accept a tensor of shape (B, *input_shape) and
  return (B, output_dim).
- Standard library plus torch only. No downloads, no file I/O, no printing.
- Compute spatial sizes rather than hard-coding a flattened dimension, so the
  module stays correct if the input shape changes.
- Derive every dimension by composing the layers you build. Where a stated
  `in_features` contradicts what the preceding layers produce, the preceding
  layers win -- build what actually connects.
- Implement each `blocks` entry as its own nn.Module class. N references to a
  block mean N separately constructed instances, never one shared module.

Output the file contents only, with no prose and no markdown fence."""

GEN = """\
Specification:

{spec}

Write model.py."""

REPAIR = """\
This model.py failed the `{stage}` gate.

--- model.py ---
{code}

--- error ---
{error}

--- specification ---
{spec}

Return the corrected model.py in full. Keep the same contract and stay faithful
to the specification; change only what the error requires."""


def _readme(spec: PaperSpec) -> str:
    unresolved = "\n".join(f"- {u}" for u in spec.unresolved) or "- none"
    assumptions = "\n".join(f"- {a}" for a in spec.assumptions) or "- none"
    return f"""# {spec.title}

Generated by RunMyPaper from the paper's specification.

```bash
pip install -r requirements.txt
python smoke.py --stage step      # shape and gradient check
python train.py --limit 256       # short run
python train.py                   # full run
```

## Not stated in the paper
{unresolved}

## Defaults applied
{assumptions}
"""


def scaffold(spec: PaperSpec, out: Path) -> Path:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name in ("data.py", "train.py", "smoke.py", "requirements.txt"):
        shutil.copy(SCAFFOLD_DIR / name, out / name)
    (out / "config.yaml").write_text(
        yaml.safe_dump(to_runtime_config(spec), sort_keys=False)
    )
    (out / "spec.json").write_text(spec.model_dump_json(indent=2))
    (out / "README.md").write_text(_readme(spec))
    return out


@dataclass
class Generated:
    """Which route produced model.py, so a report can say so."""
    path: Path
    method: str                      # "compiled" or "generated"
    fallback_reason: Optional[str] = None

    def __fspath__(self) -> str:     # still usable where a path was expected
        return str(self.path)


def write_model(spec: PaperSpec, out: Path, use_cache: bool = True,
                mode: str = CODEGEN) -> Generated:
    """Write model.py, compiling the spec when that is possible.

    Compilation is preferred because the spec already names torch.nn classes
    and their arguments: generating that from scratch spends an API request to
    reproduce information the spec already holds, and risks getting it wrong.
    """
    path = Path(out) / "model.py"
    reason = None

    if mode in ("auto", "emit"):
        try:
            path.write_text(emit.emit(spec))
            return Generated(path, "compiled")
        except ValueError as exc:
            reason = str(exc)
            if mode == "emit":
                raise SystemExit(
                    f"RMP_CODEGEN=emit but this spec cannot be compiled: {reason}")

    code = generate(SYSTEM, GEN.format(spec=spec.model_dump_json(indent=2)),
                    use_cache=use_cache)
    path.write_text(extract_code(code))
    return Generated(path, "generated", reason)


def repair_model(spec: PaperSpec, out: Path, stage: str, error: str) -> Path:
    path = Path(out) / "model.py"
    prompt = REPAIR.format(
        stage=stage,
        code=path.read_text(),
        error=error[-4000:],          # the tail holds the actual traceback
        spec=spec.model_dump_json(indent=2),
    )
    # Never cached: each repair must see the current failure.
    path.write_text(extract_code(generate(SYSTEM, prompt, use_cache=False)))
    return path
